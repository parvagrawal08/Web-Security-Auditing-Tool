"""
reports/html_report.py

Generates a self-contained HTML report for a completed scan (inline CSS,
no external assets, no scripts), readable on its own outside the app.

Sections: header/metadata, score + overall risk, executive summary,
severity summary, category summary, scan warnings (if any), detailed
findings (evidence, impact, recommendation), technical scan information,
limitations and ethical notice.

IMPORTANT SECURITY NOTE -- output encoding:
Every piece of text that ultimately came from the SCANNED SERVER itself
(header values, cookie names, CSP strings, evidence text, etc.) -- and
every other dynamic value -- is HTML-escaped via html.escape() before
being embedded. Without this, a malicious or misconfigured target could
return a header value containing markup/script that would execute when
the report is opened in a browser (stored XSS against the person running
this tool). The report also contains no <script> element and no links
built from scan data.
"""

import html
from datetime import datetime

from analysis.findings import group_by_category, sort_findings
from analysis.risk import risk_from_score_result
from analysis.summary import (
    SEVERITY_DISPLAY_ORDER, category_summary, pass_count, severity_counts,
)
from scan_controller import ScanResult
from utils.errors import explain_error

SEVERITY_COLORS = {
    "Critical": "#8B0000",
    "High": "#C0392B",
    "Medium": "#B9770E",
    "Low": "#1F6F9F",
    "Informational": "#5D6D7E",
    "Pass": "#2E7D32",
}

SCORE_BAND_COLORS = {
    "Excellent": "#2E7D32",
    "Good": "#558B2F",
    "Moderate": "#B9770E",
    "Poor": "#C0501A",
    "Critical": "#B71C1C",
}

STATE_COLORS = {
    "Issues found": "#B9770E",
    "No issues found": "#2E7D32",
    "Incomplete": "#5D6D7E",
}

ETHICAL_NOTICE = (
    "This report was generated by an automated, non-destructive web application "
    "security configuration auditing tool, for educational and authorized security "
    "testing purposes only. It must only be used against systems the operator owns or "
    "has explicit, documented authorization to test. This tool performs passive and "
    "safe configuration checks -- it does not exploit, brute-force, or attempt to "
    "damage the target in any way. Findings describe configuration weaknesses and "
    "information disclosure, not confirmed exploitation, unless explicitly stated."
)

LIMITATIONS_TEXT = (
    "This report reflects only the configuration checks listed under Technical Scan "
    "Information: HTTP/HTTPS, security headers, cookies, CORS, HTTP methods, server "
    "disclosure, TLS/SSL, and a small set of common directory paths. It does NOT "
    "include: authenticated scanning, OWASP Top 10 vulnerability testing, API/OpenAPI "
    "analysis, exhaustive directory brute-forcing, or confirmed exploitation of any "
    "finding. A clean scan does not guarantee the target is free of vulnerabilities "
    "outside this tool's scope -- it reflects only the specific checks performed. "
    "Checks that could not be completed are listed as warnings and are NOT counted as passed."
)


def _e(value) -> str:
    """Shorthand for html.escape() on any value, converting to str first."""
    return html.escape(str(value))


def build_executive_summary_text(scan_result: ScanResult) -> str:
    """Plain-text executive summary (also used by the PDF report)."""
    score = scan_result.score_result
    risk = risk_from_score_result(score)
    counts = severity_counts(scan_result.findings)
    notable = [f"{counts[level]} {level}" for level in ("Critical", "High", "Medium") if counts[level]]
    notable_text = (
        f" Notable findings: {', '.join(notable)}."
        if notable else " No Critical, High, or Medium severity findings were identified."
    )
    not_completed = len(scan_result.partial_outcomes) + len(scan_result.failed_outcomes)
    warn_text = (
        f" {not_completed} of {len(scan_result.module_outcomes)} check categories could not be "
        f"fully completed; those checks are not counted as passed."
        if not_completed else ""
    )
    return (
        f"This scan of {scan_result.target_url} produced an overall security score of "
        f"{score.score}/100 ({score.category}), an overall risk of {risk.label}, based on "
        f"{len(scan_result.findings)} checks across {len(scan_result.module_outcomes)} "
        f"categories.{notable_text}{warn_text} This score reflects configuration-level "
        f"checks only; see Limitations for scope details."
    )


def _warnings_html(scan_result: ScanResult) -> str:
    problems = scan_result.partial_outcomes + scan_result.failed_outcomes
    if not problems:
        return ""
    rows = []
    for o in problems:
        info = explain_error(o.detail or "")
        label = "Could not be completed" if o.status == "failed" else "Partially completed"
        rows.append(
            f"<tr><td>{_e(o.name)}</td><td>{_e(label)}</td>"
            f"<td>{_e(info.summary)}<br><span class='muted'>{_e(info.technical)}</span></td></tr>"
        )
    return f"""
    <div class="section">
        <h2>Scan Warnings</h2>
        <p>The following checks did not fully run. They are <strong>not</strong> reported as passed.</p>
        <table class="grid"><tr><th>Category</th><th>Status</th><th>Reason</th></tr>{''.join(rows)}</table>
    </div>"""


def _category_summary_html(scan_result: ScanResult) -> str:
    rows = []
    for row in category_summary(scan_result.findings, scan_result.score_result, scan_result.module_outcomes):
        color = STATE_COLORS.get(row["state"], "#555")
        rows.append(
            f"<tr><td>{_e(row['category'])}</td>"
            f"<td style='color:{color};font-weight:600'>{_e(row['state'])}</td>"
            f"<td>{row['checks']}</td><td>{row['issues']}</td><td>{row['passed']}</td>"
            f"<td>{row['errors']}</td><td>{_e(row['points_deducted'])}</td></tr>"
        )
    return (
        "<table class='grid'><tr><th>Category</th><th>Result</th><th>Checks</th><th>Issues</th>"
        "<th>Passed</th><th>Not completed</th><th>Points deducted</th></tr>"
        + "".join(rows) + "</table>"
    )


def _findings_html(scan_result: ScanResult, include_evidence: bool, include_recommendations: bool) -> str:
    sections = []
    for category, items in group_by_category(scan_result.findings).items():
        cards = []
        for f in sort_findings(items):
            color = SEVERITY_COLORS.get(f.severity, "#555")
            status_note = ""
            if f.status == "Error":
                status_note = " &middot; Check could not be completed"
            elif f.status == "Pass":
                status_note = " &middot; Passed"
            evidence = (
                f"<h5>Evidence</h5><pre>{_e(f.evidence)}</pre>" if include_evidence else ""
            )
            recommendation = (
                f"<h5>Recommendation</h5><p>{_e(f.recommendation)}</p>" if include_recommendations else ""
            )
            reference = f"<h5>Reference</h5><p>{_e(f.reference)}</p>" if f.reference else ""
            cards.append(f"""
            <div class="finding" style="border-left:5px solid {color};">
                <div class="finding-head">
                    <span class="badge" style="background:{color};">{_e(f.severity)}</span>
                    <span class="finding-title">{_e(f.title)}</span>
                    <span class="muted">{_e(f.check_id)}{status_note}</span>
                </div>
                <p class="muted">Category: {_e(f.category)} &middot; Scanner: {_e(f.category)}</p>
                <h5>Description</h5><p>{_e(f.description)}</p>
                {evidence}
                <h5>Impact</h5><p>{_e(f.impact)}</p>
                {recommendation}
                {reference}
            </div>""")
        sections.append(f"<h3>{_e(category)} <span class='muted'>({len(items)})</span></h3>{''.join(cards)}")
    return "".join(sections)


def generate_html_report(
    scan_result: ScanResult,
    include_evidence: bool = True,
    include_recommendations: bool = True,
) -> str:
    """Return the full HTML report as a self-contained string."""
    score = scan_result.score_result
    risk = risk_from_score_result(score)
    band_color = SCORE_BAND_COLORS.get(score.category, "#555")
    counts = severity_counts(scan_result.findings)

    severity_html = "".join(
        f'<div class="sev"><div class="sev-n" style="color:{SEVERITY_COLORS[level]}">{counts[level]}</div>'
        f'<div class="sev-l">{_e(level)}</div></div>'
        for level in SEVERITY_DISPLAY_ORDER
    ) + f'<div class="sev"><div class="sev-n" style="color:{SEVERITY_COLORS["Pass"]}">{pass_count(scan_result.findings)}</div><div class="sev-l">Passed checks</div></div>'

    settings = scan_result.settings_used or {}
    tech_rows = [
        ("Scan status", scan_result.scan_status),
        ("Duration", f"{scan_result.duration_seconds}s"),
        ("Request timeout", f"{settings.get('timeout_seconds', 'n/a')}s"),
        ("Delay between modules", f"{settings.get('delay_seconds', 'n/a')}s"),
        ("Categories scanned", ", ".join(o.name for o in scan_result.module_outcomes) or ", ".join(scan_result.modules_run)),
        ("Total checks recorded", str(len(scan_result.findings))),
        ("Scoring", f"Starts at 100; deductions: {score.total_deductions} points (Phase 1 scoring model)"),
        ("Report generated", datetime.now().strftime("%Y-%m-%d %H:%M:%S")),
    ]
    tech_html = "".join(f"<tr><td>{_e(k)}</td><td>{_e(v)}</td></tr>" for k, v in tech_rows)

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Security Audit Report - {_e(scan_result.target_url)}</title>
<style>
    body {{ font-family: -apple-system, "Segoe UI", Arial, sans-serif; margin: 0; background: #eef1f4; color: #1c2430; line-height: 1.5; }}
    .container {{ max-width: 920px; margin: 0 auto; padding: 32px; background: #fff; }}
    h1 {{ margin: 0 0 4px; font-size: 26px; letter-spacing: .3px; }}
    h2 {{ border-bottom: 2px solid #d5dbe1; padding-bottom: 6px; margin-top: 36px; }}
    h3 {{ margin-top: 26px; }}
    h5 {{ margin: 10px 0 2px; font-size: 12px; text-transform: uppercase; letter-spacing: .6px; color: #5b6673; }}
    .muted {{ color: #6b7683; font-size: 13px; }}
    .notice {{ background: #fff6dd; border: 1px solid #ecd58a; padding: 12px 14px; border-radius: 6px; font-size: 13px; margin: 18px 0; }}
    table.meta, table.grid {{ width: 100%; border-collapse: collapse; margin: 12px 0; font-size: 14px; }}
    table.meta td {{ padding: 6px 10px; border-bottom: 1px solid #e6eaee; }}
    table.meta td:first-child {{ width: 200px; font-weight: 600; color: #4a5561; }}
    table.grid th {{ text-align: left; background: #f1f4f7; padding: 7px 10px; font-size: 12px; text-transform: uppercase; letter-spacing: .5px; }}
    table.grid td {{ padding: 7px 10px; border-bottom: 1px solid #e6eaee; vertical-align: top; }}
    .hero {{ display: flex; gap: 24px; align-items: center; margin: 24px 0; flex-wrap: wrap; }}
    .score {{ font-size: 58px; font-weight: 700; color: {band_color}; line-height: 1; }}
    .score small {{ font-size: 22px; color: #6b7683; }}
    .risk {{ font-size: 20px; font-weight: 600; color: {band_color}; }}
    .sevs {{ display: flex; gap: 8px; flex-wrap: wrap; margin: 12px 0; }}
    .sev {{ flex: 1 1 110px; border: 1px solid #e0e5ea; border-radius: 6px; padding: 10px; text-align: center; }}
    .sev-n {{ font-size: 28px; font-weight: 700; }}
    .sev-l {{ font-size: 12px; color: #5b6673; }}
    .finding {{ border: 1px solid #e0e5ea; border-radius: 6px; padding: 12px 16px; margin: 12px 0; page-break-inside: avoid; }}
    .finding-head {{ display: flex; gap: 10px; align-items: center; flex-wrap: wrap; }}
    .finding-title {{ font-weight: 600; font-size: 16px; }}
    .badge {{ color: #fff; padding: 2px 10px; border-radius: 10px; font-size: 12px; font-weight: 700; }}
    .finding p {{ margin: 3px 0; font-size: 14px; }}
    pre {{ background: #f3f5f7; border: 1px solid #e0e5ea; padding: 8px 10px; border-radius: 4px; white-space: pre-wrap; word-break: break-word; font-size: 12.5px; margin: 3px 0; }}
    .footer {{ background: #f1f4f7; padding: 12px 14px; border-radius: 6px; font-size: 13px; color: #4a5561; margin-top: 36px; }}
    @media print {{ body {{ background: #fff; }} .container {{ padding: 0; }} }}
</style>
</head>
<body>
<div class="container">
    <h1>WEB APPLICATION SECURITY AUDIT REPORT</h1>
    <p class="muted">Automated, non-destructive configuration scan</p>

    <div class="notice">{_e(ETHICAL_NOTICE)}</div>

    <table class="meta">
        <tr><td>Target</td><td>{_e(scan_result.target_url)}</td></tr>
        <tr><td>Scan Date/Time</td><td>{_e(scan_result.scan_timestamp)}</td></tr>
        <tr><td>Scan Status</td><td>{_e(scan_result.scan_status)}</td></tr>
    </table>

    <div class="hero">
        <div class="score">{score.score}<small> / 100</small></div>
        <div>
            <div class="risk">{_e(risk.label)}</div>
            <div class="muted">Security score band: {_e(score.category)}</div>
        </div>
    </div>

    <h2>Executive Summary</h2>
    <p>{_e(build_executive_summary_text(scan_result))}</p>

    <h2>Severity Summary</h2>
    <div class="sevs">{severity_html}</div>

    <h2>Category Summary</h2>
    {_category_summary_html(scan_result)}
    {_warnings_html(scan_result)}

    <h2>Detailed Findings</h2>
    {_findings_html(scan_result, include_evidence, include_recommendations)}

    <h2>Technical Scan Information</h2>
    <table class="meta">{tech_html}</table>

    <h2>Limitations</h2>
    <p>{_e(LIMITATIONS_TEXT)}</p>

    <div class="footer">
        This report was generated automatically and should be reviewed by a qualified
        person before acting on its recommendations. Findings labeled as configuration
        weaknesses or information disclosure are not confirmed exploits.
    </div>
</div>
</body>
</html>"""


def save_html_report(scan_result: ScanResult, output_path: str, **kwargs) -> None:
    """Write the HTML report to disk at the given path."""
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(generate_html_report(scan_result, **kwargs))
